# REVIEWER NOTE: Root Domain Selection Rationale
# =============================================================================
"""
Root Domain Selection Process for Mode B Evaluation
-----------------------------------------------------
The four Mode B root domains were selected through a four-stage process
designed to ensure that (a) the registered domains are statistically
grounded in real-world naming conventions, (b) they are indistinguishable
from legitimate newly-registered domains by visual inspection, and (c)
the root domain length is approximately constant across chunk-size classes
so that fqdn_length differences between classes reflect chunk size only.

Stage 1 -- N-gram extraction from the Cloudflare Radar Top 1M dataset
  The 20 most-frequent 2-grams and 3-grams were extracted from the
  Cloudflare Radar Top 1M domain dataset (Table 2 of the paper) using
  the analyze_most_common_ngrams() function of create_full_baseline_v3.py.
  This dataset represents the most popular registered domains observed
  globally over the period 15-22 September 2025, making its N-gram
  distribution the most authoritative available characterisation of
  real-world registered domain naming conventions.

Stage 2 -- Dot-filtering to extract label-valid seeds
  N-grams containing dot characters were excluded. Dots are structural
  label separators in the DNS protocol (RFC 1035) and are not label-
  internal characters. At N=2 and N=3, 17 and 5 valid (dot-free) seeds
  survived respectively, forming a 22-seed set:
    2-grams: co, in, de, re, ne, er, et, al, es, en, or, an, on,
             ar, te, st (17 seeds)
    3-grams: com, net, org, ing, lin (5 seeds)
  At N>=4, all top-20 entries contained dots and were entirely excluded.

Stage 3 -- Root Domain-LSTM generation at temperature=0.8
  Each of the 22 seeds was fed to the Root Domain-LSTM model at
  temperature=0.8, which was empirically identified as the optimal
  trade-off between generation diversity and output realism in the
  qualitative evaluation (rootdomain_QE_testdataset_lstm_model_v10.py).
  This produced 22 candidate registered domain strings such as
  commandobet.com, stickersbot.app, compusolid.com, ordersropul.com,
  andrewcounty.com, art-360.com, essentialnotes.com, etc.

Stage 4 -- Selection criteria applied to 22 candidates
  Four criteria were applied to select the final four root domains,
  one per chunk-size class:

  Criterion 1 -- Single-label TLD only (no compound ccTLDs).
    Domains with compound TLDs such as .com.br or .co.uk were excluded
    because they produce domain_depth=4 FQDNs when combined with a
    subdomain, whereas the benign training pool and all Mode A test
    FQDNs are uniformly domain_depth=3. A depth=4 root domain would
    affect the num_labels and avg_label_length Jawad features
    independently of chunk size, introducing an uncontrolled confound.
    This criterion eliminated netindo.com.br from the candidate set.

  Criterion 2 -- Plausible total domain length (11-20 chars).
    Domains shorter than 11 characters (e.g. inmig.net at 9 chars,
    eniz.plus at 9 chars) were excluded as unrealistically short for
    a domain that would plausibly be registered for a sustained
    exfiltration campaign. Domains longer than 20 characters
    (templettomatrimony.com at 22 chars, newhotelstaxingstudio.com at
    25 chars) were excluded as unusually long and potentially
    attention-drawing.

  Criterion 3 -- Similar total length across classes (spread <= 3 chars).
    The four selected domains must have similar total character lengths
    so that fqdn_length differences between the four chunk-size classes
    reflect the chunk size alone. The selected domains span 14-16
    characters (spread = 2 chars), which is negligible relative to
    the chunk-size differences between classes (7, 13, 26, 52 chars).

  Criterion 4 -- No trademark, inappropriate, or implausible content.
    Domains containing recognised trademarks (starbucks.com appeared
    in generation at temperature=0.5) or inappropriate vocabulary
    (temperature=1.2 outputs) were excluded.

Final selection:
  compusolid.com   (14 chars) -- 4-byte  / 7-char  chunk class
  commandobet.com  (15 chars) -- 8-byte  / 13-char chunk class
  ordersropul.com  (15 chars) -- 16-byte / 26-char chunk class
  andrewcounty.com (16 chars) -- 32-byte / 52-char chunk (negative control)
"""
