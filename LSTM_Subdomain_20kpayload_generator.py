def write_report(test_loss, test_accuracy, df_out, class_stats):
    """Write a combined quantitative + Mode B generation report."""
    lines = []
    lines.append("=" * 65)
    lines.append("  Mode B Subdomain-LSTM -- Generation Report")
    lines.append("=" * 65)

    lines.append(f"\n  Model          : {SUBDOMAIN_MODEL_PATH}")
    lines.append(f"  Temperature    : {TEMPERATURE}")
    lines.append(f"  Max attempts   : {MAX_ATTEMPTS}")

    if test_loss is not None:
        lines.append(f"\n  --- Quantitative Evaluation ---")
        lines.append(f"  Test Loss      : {test_loss:.4f}")
        lines.append(f"  Test Accuracy  : {test_accuracy:.4f}")

    if df_out is not None:
        total   = len(df_out)
        valid   = df_out['valid'].sum()
        invalid = total - valid

        lines.append(f"\n  --- Mode B Generation Summary ---")
        lines.append(f"  Total payload instances : {total:,}")
        lines.append(f"  Valid FQDNs generated   : {valid:,} "
                     f"({valid/total*100:.2f}%)")
        lines.append(f"  Discarded (invalid)     : {invalid:,} "
                     f"({invalid/total*100:.2f}%)")

        lines.append(f"\n  --- Per Chunk-Size Class ---")
        lines.append(f"  {'Bytes':>6}  {'Root domain':<20}  "
                     f"{'Valid':>7}  {'Invalid':>8}  "
                     f"{'Valid%':>7}  {'Avg attempts':>13}")
        lines.append(f"  {'-'*68}")
        for byte_len, stats in class_stats.items():
            v  = stats['valid']
            iv = stats['invalid']
            n  = v + iv
            avg_att = stats['attempts_total'] / n if n > 0 else 0
            lines.append(
                f"  {byte_len:>6}  "
                f"{MODE_B_ROOT_DOMAINS[byte_len]:<20}  "
                f"{v:>7,}  {iv:>8,}  "
                f"{v/n*100:>6.1f}%  "
                f"{avg_att:>13.2f}"
            )

        lines.append(f"\n  --- Discard Reason Distribution ---")
        if invalid > 0:
            reason_counts = (df_out[df_out['valid'] == 0]
                               ['discard_reason'].value_counts())
            for reason, count in reason_counts.items():
                lines.append(f"    {reason:<25}: {count:,}")
        else:
            lines.append("    No discards.")

        lines.append(f"\n  --- Sample Outputs (first valid per class) ---")
        for byte_len in MODE_B_ROOT_DOMAINS:
            sub = df_out[
                (df_out['chunk_size_bytes'] == byte_len) &
                (df_out['valid'] == 1)
            ].head(3)
            lines.append(f"\n  {byte_len}-byte chunks "
                         f"(~{int(sub.iloc[0]['chunk_base32_len'])}-char "
                         f"Base32 seed):")
            for _, r in sub.iterrows():
                lines.append(f"    Seed : {r['chunk_base32']}")
                lines.append(f"    Raw  : {r['generated_raw']}")
                lines.append(f"    Final: {r['model_output']}")
                lines.append("")

    report_text = '\n'.join(lines)
    print('\n' + report_text)
    with open(OUTPUT_REPORT, 'w', encoding='utf-8') as f:
        f.write(report_text)
    print(f"\n  Report saved -> {OUTPUT_REPORT}")

