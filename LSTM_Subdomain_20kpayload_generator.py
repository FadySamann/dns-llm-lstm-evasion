# Subdomain-LSTM model
SUBDOMAIN_MODEL_PATH = 'LSTM_subdomian_generator_best_overall_model.keras'
TEST_TFRECORD        = 'subdomain_test.tfrecord'
METRICS_OUTPUT       = 'subdomain_test_quantitative_results.csv'

MAXLEN     = 85
VOCAB_SIZE = 41
BATCH_SIZE = 128

# Payload corpus (from payload_pipeline.py)
PAYLOAD_CSV = 'payload_corpus.csv'

# Mode B root domain assignment (Method 2: one root domain per class)
# Keys are chunk_size_bytes values from payload_corpus.csv
MODE_B_ROOT_DOMAINS = {
    4:  'compusolid.com',    # 14 chars -- 4-byte / 7-char chunk class
    8:  'commandobet.com',   # 15 chars -- 8-byte / 13-char chunk class
    16: 'ordersropul.com',   # 15 chars -- 16-byte / 26-char chunk class
    32: 'andrewcounty.com',  # 16 chars -- 32-byte / 52-char chunk (neg. control)
}

# Generation parameters
TEMPERATURE  = 0.8   # confirmed as the best balance of realism and variety
MAX_GEN_LEN  = 80    # maximum characters the model can generate per call
MAX_ATTEMPTS = 5     # retry attempts per payload if generation is invalid

OUTPUT_CSV   = 'modeb_lstm_fqdns_v2.csv'
OUTPUT_REPORT = 'modeb_lstm_report_v2.txt'

# =============================================================================
# CHARACTER MAPPING
# Identical to rootdomain_QE_testdataset_lstm_model_v10.py and the
# Subdomain-LSTM training pipeline -- must not be modified.
# =============================================================================

all_chars   = (['<PAD>'] + list(string.ascii_lowercase) +
                list(string.digits) + ['_', '-', '.'] + ['<EOS>'])
char_to_int = {char: i for i, char in enumerate(all_chars)}
int_to_char = {i: char for i, char in enumerate(all_chars)}

# =============================================================================
# TFRecord PARSING (quantitative evaluation -- unchanged from v10)
# =============================================================================

def parse_tfrecord_fn(example):
    feature_description = {
        'x': tf.io.FixedLenFeature([MAXLEN], tf.int64),
        'y': tf.io.FixedLenFeature([VOCAB_SIZE], tf.float32),
    }
    example = tf.io.parse_single_example(example, feature_description)
    return tf.cast(example['x'], tf.int32), example['y']

# =============================================================================
# SAMPLING & GENERATION
# Ported directly from rootdomain_QE_testdataset_lstm_model_v10.py,
# with MAXLEN updated to 85 for the Subdomain model.
# =============================================================================

def sample(preds, temperature=1.0):
    """Temperature-scaled categorical sampling over the vocabulary."""
    preds     = np.asarray(preds).astype('float64')
    preds     = np.log(preds + 1e-10) / temperature
    exp_preds = np.exp(preds)
    preds     = exp_preds / np.sum(exp_preds)
    probas    = np.random.multinomial(1, preds, 1)
    return np.argmax(probas)


def generate_fqdn(model, seed_text, max_gen_len=MAX_GEN_LEN,
                  temperature=TEMPERATURE):
    """
    Generate a full FQDN from a seed string using the Subdomain-LSTM.

    The seed is treated as the beginning of the subdomain label.
    Generation continues character-by-character until <EOS> is
    predicted or max_gen_len is reached.

    For Mode B, seed_text is a Base32-encoded payload chunk
    (e.g. 'ab3xkf2' for a 4-byte chunk). The model completes
    the subdomain with CDN-mimicking characters, then appends
    the original root domain from its training distribution.
    The original root domain is stripped and replaced with the
    Mode B root domain in replace_root_domain() below.
    """
    generated = seed_text.lower()
    for _ in range(max_gen_len):
        if len(generated) >= MAXLEN:          # <-- add this guard
            break
        encoded_seq = [char_to_int[c] for c in generated if c in char_to_int]
        padded_seq  = pad_sequences([encoded_seq], maxlen=MAXLEN, padding='pre')
        preds       = model.predict(padded_seq, verbose=0)[0]
        next_index  = sample(preds, temperature)
        next_char   = int_to_char[next_index]
        if next_char == '<EOS>':
            break
        generated  += next_char
    return generated

# =============================================================================
# ROOT DOMAIN REPLACEMENT
# =============================================================================

def extract_subdomain_label(fqdn: str) -> str:
    """
    Extract the subdomain portion of a generated FQDN -- everything
    to the left of the registered domain (SLD + TLD).

    Uses tldextract to correctly identify the registered domain
    boundary, handling both simple TLDs (.com, .net) and compound
    ccTLDs (.com.br, .co.uk) in the original generated string.

    Examples:
      "ab3xkf2qr7ty.github.io"       -> "ab3xkf2qr7ty"
      "d2gqczba54xr0r.cloudfront.net" -> "d2gqczba54xr0r"
      "a.b.akamaihd.net"              -> "a.b"
    """
    fqdn  = fqdn.strip().lower()
    ext   = tldextract.extract(fqdn)
    if not ext.suffix or not ext.domain:
        return ''
    # subdomain is everything tldextract identifies as the subdomain
    # component (left of the registered domain)
    return ext.subdomain


def replace_root_domain(generated_fqdn: str,
                        mode_b_root: str) -> str | None:
    """
    Strip the original root domain from a generated FQDN and replace
    it with the Mode B root domain assigned to this chunk-size class.

    Returns the final FQDN string, or None if the result is invalid:
      - Empty subdomain (structural collapse during generation)
      - Final FQDN exceeds 253 characters (RFC 1035 total limit)
      - Any individual label exceeds 63 characters (RFC 1035 label limit)
      - Subdomain contains characters invalid for DNS labels

    Parameters
    ----------
    generated_fqdn : str
        Full FQDN output by the Subdomain-LSTM model, e.g.
        "ab3xkf2qr7ty.github.io"
    mode_b_root : str
        The Mode B registered domain for this chunk-size class, e.g.
        "compusolid.com"
    """
    subdomain = extract_subdomain_label(generated_fqdn)
    if not subdomain:
        return None

    final_fqdn = f"{subdomain}.{mode_b_root}"

    # RFC 1035 structural validation
    if len(final_fqdn) > 253:
        return None
    labels = final_fqdn.split('.')
    if any(len(label) > 63 or len(label) == 0 for label in labels):
        return None

    return final_fqdn

# =============================================================================
# QUANTITATIVE EVALUATION (unchanged from v10)
# =============================================================================

def run_quantitative_evaluation(model):
    """Evaluate the Subdomain-LSTM on the held-out test TFRecord."""
    if not os.path.exists(TEST_TFRECORD):
        print(f"  WARNING: {TEST_TFRECORD} not found -- skipping metrics.")
        return None, None

    print(f"  Loading test dataset: {TEST_TFRECORD} ...")
    test_dataset = (tf.data.TFRecordDataset(TEST_TFRECORD)
                      .map(parse_tfrecord_fn)
                      .batch(BATCH_SIZE)
                      .prefetch(tf.data.AUTOTUNE))

    print("  Evaluating ...")
    results      = model.evaluate(test_dataset, verbose=1)
    test_loss    = results[0]
    test_accuracy = results[1]

    print(f"\n  Test Loss     : {test_loss:.4f}")
    print(f"  Test Accuracy : {test_accuracy:.4f}")

    pd.DataFrame({
        'Metric': ['Test Loss', 'Test Accuracy'],
        'Value':  [test_loss, test_accuracy]
    }).to_csv(METRICS_OUTPUT, index=False)
    print(f"  Metrics saved -> {METRICS_OUTPUT}")

    return test_loss, test_accuracy

