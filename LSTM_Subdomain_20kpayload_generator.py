def run_modeb_generation(model):
    """
    Generate Mode B exfiltration FQDNs from Base32 payload chunks.

    For each row in payload_corpus.csv:
      1. Use chunk_base32 as the Subdomain-LSTM seed
      2. Generate a full FQDN (subdomain + original root domain)
      3. Strip original root domain; replace with Mode B root domain
         for this chunk_size_bytes class
      4. Validate RFC 1035 constraints
      5. Retry up to MAX_ATTEMPTS times if invalid

    Output columns
    --------------
    payload_id          : from payload_corpus.csv
    chunk_size_bytes    : from payload_corpus.csv (4 / 8 / 16 / 32)
    chunk_base32        : the payload chunk used as seed
    chunk_base32_len    : character length of the Base32 chunk
    approx_seed_ratio   : estimated seed ratio vs benign mean subdomain
    model_freedom_chars : chars available for model to add as cover
    generated_raw       : raw FQDN output by the Subdomain-LSTM
    subdomain_extracted : subdomain label extracted from generated_raw
    mode_b_root_domain  : Mode B root domain assigned to this class
    model_output        : final FQDN after root domain replacement
    valid               : 1 = RFC-valid and used, 0 = discarded
    discard_reason      : reason for discard if valid == 0
    attempts            : number of generation attempts needed
    """
    if not os.path.exists(PAYLOAD_CSV):
        print(f"  ERROR: {PAYLOAD_CSV} not found.")
        print(f"  Run payload_pipeline.py first to generate the payload corpus.")
        return None

    print(f"\n  Loading payload corpus: {PAYLOAD_CSV} ...")
    df_payload = pd.read_csv(PAYLOAD_CSV, dtype=str, keep_default_na=False)
    # Restore integer type for chunk_size_bytes lookup
    df_payload['chunk_size_bytes'] = df_payload['chunk_size_bytes'].astype(int)
    print(f"  Loaded {len(df_payload):,} payload instances across "
          f"{df_payload['chunk_size_bytes'].nunique()} chunk-size classes")

    print(f"\n  Mode B root domain assignments:")
    for byte_len, root in MODE_B_ROOT_DOMAINS.items():
        n = (df_payload['chunk_size_bytes'] == byte_len).sum()
        b32_len = df_payload[df_payload['chunk_size_bytes'] == byte_len][
            'chunk_base32_len'].iloc[0]
        print(f"    {byte_len:>3}-byte / {int(b32_len):>2}-char chunks "
              f"({n:,} instances) -> {root}  "
              f"(total FQDN mean length ~"
              f"{int(b32_len) + 1 + len(root)}+ chars)")

    print(f"\n  Generating Mode B FQDNs ...")
    print(f"  Temperature   : {TEMPERATURE}")
    print(f"  Max attempts  : {MAX_ATTEMPTS} per payload\n")

    rows = []
    class_stats = {b: {'valid': 0, 'invalid': 0, 'attempts_total': 0}
                   for b in MODE_B_ROOT_DOMAINS}

    total = len(df_payload)
    for idx, row in df_payload.iterrows():
        if (idx + 1) % 500 == 0:
            print(f"  Progress: {idx+1:,} / {total:,}  "
                  f"({(idx+1)/total*100:.1f}%)")

        chunk_bytes = int(row['chunk_size_bytes'])
        chunk_b32   = str(row['chunk_base32'])
        mode_b_root = MODE_B_ROOT_DOMAINS.get(chunk_bytes)
        if mode_b_root is None:
            continue

        final_fqdn    = None
        generated_raw = ''
        subdomain_ext = ''
        discard_reason = ''
        attempts = 0

        for attempt in range(1, MAX_ATTEMPTS + 1):
            attempts = attempt
            raw = generate_fqdn(model, seed_text=chunk_b32,
                                 temperature=TEMPERATURE)
            generated_raw = raw

            result = replace_root_domain(raw, mode_b_root)

            if result is not None:
                # Extract the subdomain for the record
                subdomain_ext = extract_subdomain_label(raw)
                final_fqdn    = result
                discard_reason = ''
                break
            else:
                # Diagnose the reason for this attempt's failure
                sub = extract_subdomain_label(raw)
                if not sub:
                    discard_reason = 'empty_subdomain'
                elif len(f"{sub}.{mode_b_root}") > 253:
                    discard_reason = 'fqdn_too_long'
                else:
                    discard_reason = 'label_too_long'

        is_valid = 1 if final_fqdn is not None else 0

        rows.append({
            'payload_id':           row['payload_id'],
            'chunk_size_bytes':     chunk_bytes,
            'chunk_base32':         chunk_b32,
            'chunk_base32_len':     int(row['chunk_base32_len']),
            'approx_seed_ratio':    row['approx_seed_ratio'],
            'model_freedom_chars':  row['model_freedom_chars'],
            'generated_raw':        generated_raw,
            'subdomain_extracted':  subdomain_ext,
            'mode_b_root_domain':   mode_b_root,
            'model_output':         final_fqdn if final_fqdn else '',
            'valid':                is_valid,
            'discard_reason':       discard_reason if not is_valid else '',
            'attempts':             attempts,
        })

        class_stats[chunk_bytes]['valid' if is_valid else 'invalid'] += 1
        class_stats[chunk_bytes]['attempts_total'] += attempts

    df_out = pd.DataFrame(rows)
    df_out.to_csv(OUTPUT_CSV, index=False)

    return df_out, class_stats

