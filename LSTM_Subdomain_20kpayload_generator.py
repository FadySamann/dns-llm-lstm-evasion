"""
subdomain_lstm_modeb.py
========================
Mode B DNS Exfiltration Simulation -- Subdomain-LSTM Generation
================================================================
Extends subdomain_QE_testdataset_lstm_model_v10.py with:

  1. Quantitative evaluation on the held-out test TFRecord (unchanged)
  2. Mode B FQDN generation:
       a. Loads the payload corpus from payload_corpus.csv
          (produced by payload_pipeline.py)
       b. Uses each Base32 chunk as the seed for the Subdomain-LSTM
          model -- the model treats the chunk as a partial subdomain
          prefix and generates a realistic CDN-like completion
       c. Strips the original root domain from the generated FQDN
          and replaces it with the Mode B root domain assigned to
          that chunk-size class (Method 2: one root domain per class,
          mirroring real attacker practice of registering one domain
          per exfiltration campaign)
       d. Saves the final FQDNs to a structured CSV for evaluation
          by the multi-detector pipeline (jawad_isolation_forest.py)

Mode B root domain assignment (Method 2 -- one per chunk-size class)
----------------------------------------------------------------------
Root domains were generated by the Root Domain-LSTM model at
temperature=0.8 using the 21 most-frequent valid (dot-free)
2-gram and 3-gram seeds from the Cloudflare Radar Top 1M dataset.
See reviewer note at the bottom of this file for the full selection
rationale.

  4-byte  class (7-char  chunk) -> compusolid.com     (length 14)
  8-byte  class (13-char chunk) -> commandobet.com    (length 15)
  16-byte class (26-char chunk) -> ordersropul.com    (length 15)
  32-byte class (52-char chunk) -> andrewcounty.com   (length 16)
         [negative control: chunk exceeds mean subdomain length]

The four root domains span a total-length range of 14-16 characters
(spread = 2 chars), ensuring that fqdn_length differences between
chunk-size classes are driven by the chunk itself, not by root
domain length variation.

Root domain replacement logic
------------------------------
The Subdomain-LSTM generates a full FQDN including an original root
domain from its training distribution (e.g. github.io, akamaihd.net).
Replacement proceeds as follows:

  generated  = "ab3xkf2qr7ty.github.io"
  subdomain  = "ab3xkf2qr7ty"        (everything left of first dot
                                       that separates subdomain from SLD)
  mode_b_rd  = "compusolid.com"
  final_fqdn = "ab3xkf2qr7ty.compusolid.com"

Edge cases handled:
  - Generated string has no dot -> discard (structural collapse)
  - Generated subdomain is empty -> discard
  - Final FQDN exceeds 253 chars (RFC 1035) -> discard
  - Any label in final FQDN exceeds 63 chars (RFC 1035) -> discard
"""

